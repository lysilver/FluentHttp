using FluentHttp.SourceGenerator.Core;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace FluentHttp.SourceGenerator
{
    /// <summary>
    /// 生成接口实现类，实现类调用 FluentHttp.Ext 中的 HttpExt 扩展方法。
    /// </summary>
    [Generator]
    public class HttpIncrementalGenerator : IIncrementalGenerator
    {
        private const string FluentHttpInterfaceAttributeName = "FluentHttp.Abstractions.FluentHttpAttribute";

        private static readonly string[] ExtraUsings =
        [
            "System",
            "System.Collections.Generic",
            "System.Linq",
            "System.Net.Http",
            "System.Threading",
            "System.Threading.Tasks",
            "FluentHttp.Abstractions",
            "FluentHttp.Ext",
            "FluentHttp.Ext.LoadBalancing",
            "Microsoft.Extensions.Http",
        ];

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            IncrementalValueProvider<ImmutableArray<INamedTypeSymbol>> fluentHttpInterfaces = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    FluentHttpInterfaceAttributeName,
                    predicate: static (node, _) => node is InterfaceDeclarationSyntax,
                    transform: static (ctx, _) => (INamedTypeSymbol)ctx.TargetSymbol)
                .Collect();

            context.RegisterSourceOutput(fluentHttpInterfaces, static (context, interfaces) =>
            {
                foreach (var interfaceSymbol in interfaces)
                {
                    context.AddSource(
                        $"{GetImplClassName(interfaceSymbol)}.g.cs",
                        SourceText.From(GenerateInterfaceImplSource(interfaceSymbol), Encoding.UTF8));
                }

                if (interfaces.Length > 0)
                {
                    context.AddSource(
                        "ServiceCollectionExtG.g.cs",
                        SourceText.From(GenerateServiceCollectionExtSource([.. interfaces]), Encoding.UTF8));
                }
            });
        }

        #region 代码生成

        private static string GenerateInterfaceImplSource(INamedTypeSymbol interfaceSymbol)
        {
            var interfaceAppId = GetNamedArgumentValue(interfaceSymbol, DaprConst.AppId);
            var interfaceUrl = GetNamedArgumentValue(interfaceSymbol, DaprConst.Url);
            var interfaceClientName = GetNamedArgumentValue(interfaceSymbol, DaprConst.ClientName);

            var implClassName = GetImplClassName(interfaceSymbol);
            var namespaceName = interfaceSymbol.ContainingNamespace.ToDisplayString();

            var builder = new AdvancedExtensionBuilder();
            builder
                .WithNullable()
                .AppendAutoGeneratedComment()
                .WithUsingsList(GetUsings(interfaceSymbol));

            builder
                .BeginNamespace(namespaceName)
                .BeginClassType($"public partial class {implClassName} : {interfaceSymbol.Name}")
                .WithLine("private readonly IHttpClientFactory _clientFactory;")
                .WithLine("private readonly IHttpClientAdapter _clientAdapter;")
                .WithLine()
                .WithBlock($"public {implClassName}(IHttpClientFactory clientFactory, IHttpClientAdapter clientAdapter)", b =>
                {
                    b.WithLine("_clientFactory = clientFactory;")
                     .WithLine("_clientAdapter = clientAdapter;");
                })
                .WithLine();

            foreach (var method in interfaceSymbol.GetMembers().OfType<IMethodSymbol>())
            {
                GenerateMethod(builder, interfaceSymbol, method, interfaceAppId, interfaceUrl, interfaceClientName);
                builder.WithLine();
            }

            return builder.EndClass().EndNamespace().ToString();
        }

        private static void GenerateMethod(AdvancedExtensionBuilder builder,
            INamedTypeSymbol interfaceSymbol,
            IMethodSymbol method,
            string interfaceAppId,
            string interfaceUrl,
            string interfaceClientName)
        {
            var methodSyntax = method.DeclaringSyntaxReferences
                .Select(static x => x.GetSyntax())
                .OfType<MethodDeclarationSyntax>()
                .FirstOrDefault()
                ?? throw new InvalidOperationException($"Cannot resolve the declaration of method {method.Name} on {interfaceSymbol.Name}.");

            var methodAppId = GetNamedArgumentValue(method, DaprConst.AppId);
            var methodUrl = GetNamedArgumentValue(method, DaprConst.Url);
            var httpReturnType = GetNamedArgumentValue(method, DaprConst.HttpReturnType);
            var httpMethodValue = GetNamedArgumentValue(method, DaprConst.MemberHttpMethod);
            var useJsonPatch = GetNamedArgumentValue(method, DaprConst.UseJsonPatch);
            var patchContentTypeArg = string.Equals(useJsonPatch, "False", StringComparison.OrdinalIgnoreCase)
                ? ", contentType: HttpContentType.Json"
                : string.Empty;

            var appId = string.IsNullOrWhiteSpace(methodAppId) ? interfaceAppId : methodAppId;
            var url = new RoslynSymbol { Url = interfaceUrl }.GetUrl(methodUrl ?? string.Empty);

            var parameters = GetParameters(methodSyntax, method);
            var bodyParam = parameters.FirstOrDefault(p => !p.IsPath);
            var httpMethodName = GetHttpMethodName(method);
            var returnArg = GetReturnTypeArgument(methodSyntax);
            var signature = string.Join(", ", parameters.Select(p => $"{p.Type} {p.Name}"));
            var returnType = methodSyntax.ReturnType.ToString().Trim();
            var createClientCall = string.IsNullOrWhiteSpace(interfaceClientName)
                ? "_clientFactory.CreateClient()"
                : $"_clientFactory.CreateClient(\"{EscapeStringLiteral(interfaceClientName)}\")";
            var appIdExpr = $"\"{EscapeStringLiteral(appId ?? string.Empty)}\"";
            var hasPathParams = parameters.Any(p => p.IsPath);
            var urlExpr = hasPathParams
                ? "$\"" + EscapeStringLiteral(url) + "\""
                : "\"" + EscapeStringLiteral(url) + "\"";
            var queryParameters = httpMethodName == "GET"
                ? parameters.Where(p => !p.IsPath && !p.IsFilePath).ToList()
                : [];
            var hasUrlVariable = queryParameters.Count > 0;
            var urlArg = hasUrlVariable ? "url" : urlExpr;

            builder.WithBlock($"public async {returnType} {methodSyntax.Identifier.Text}({signature})", b =>
            {
                b.WithLine($"using var client = {createClientCall};");

                if (hasUrlVariable)
                {
                    b.WithLine($"var url = {urlExpr};");
                    var queryItems = string.Join(", ", queryParameters.Select(p => $"\"{p.Name}=\" + {p.Name}"));
                    b.WithLine($"var query = string.Join(\"&\", new[] {{ {queryItems} }});")
                     .WithLine($"url += string.IsNullOrEmpty(query) ? \"\" : \"?\" + query;");
                }

                if (IsStringReturn(httpReturnType))
                {
                    var httpMethodLiteral = GetHttpMethodLiteral(httpMethodName);
                    var bodyArg = bodyParam?.Name ?? "null";
                    b.WithLine($"using var res = await client.HttpResponseMessageAsync<object>(_clientAdapter, {appIdExpr}, {urlArg}, {httpMethodLiteral}, {bodyArg});")
                     .WithLine("res.EnsureSuccessStatusCode();")
                     .WithLine("return await res.Content.ReadAsStringAsync();");
                }
                else
                {
                    b.WithLine(GenerateCall(httpMethodName, httpMethodValue, returnArg, bodyParam, parameters, appIdExpr, urlArg, patchContentTypeArg));
                    b.WithLine("return res!;");
                }
            });
        }

        private static bool IsStringReturn(string httpReturnType)
        {
            return string.Equals(httpReturnType, "String", StringComparison.OrdinalIgnoreCase)
                || string.Equals(httpReturnType, "FluentHttp.Abstractions.HttpReturnType.String", StringComparison.Ordinal)
                || string.Equals(httpReturnType, "HttpReturnType.String", StringComparison.Ordinal)
                || string.Equals(httpReturnType, "1", StringComparison.Ordinal);
        }

        private static string GetHttpMethodLiteral(string httpMethodName)
        {
            return httpMethodName switch
            {
                "POST" => "HttpMethod.Post",
                "PUT" => "HttpMethod.Put",
                "DELETE" => "HttpMethod.Delete",
                "Patch" => "HttpMethod.Patch",
                _ => "HttpMethod.Get",
            };
        }

        private static string GenerateCall(string httpMethodName, string httpMethodValue, string returnArg, GeneratedParam bodyParam, List<GeneratedParam> parameters, string appIdExpr, string urlArg, string patchContentTypeArg)
        {
            return httpMethodName switch
            {
                "GET" => $"var res = await client.HttpGet<{returnArg}>(_clientAdapter, {appIdExpr}, {urlArg});",

                "POST" => bodyParam is not null
                    ? $"var res = await client.HttpPost<{returnArg}, {bodyParam.Type}>(_clientAdapter, {appIdExpr}, {urlArg}, {bodyParam.Name});"
                    : $"var res = await client.HttpPost<{returnArg}, object>(_clientAdapter, {appIdExpr}, {urlArg}, null);",

                "PUT" => bodyParam is not null
                    ? $"var res = await client.HttpPut<{returnArg}, {bodyParam.Type}>(_clientAdapter, {appIdExpr}, {urlArg}, {bodyParam.Name});"
                    : $"var res = await client.HttpPut<{returnArg}, object>(_clientAdapter, {appIdExpr}, {urlArg}, null);",

                "Patch" => bodyParam is not null
                    ? $"var res = await client.HttpPatch<{returnArg}, {bodyParam.Type}>(_clientAdapter, {appIdExpr}, {urlArg}, {bodyParam.Name}{patchContentTypeArg});"
                    : $"var res = await client.HttpPatch<{returnArg}, object>(_clientAdapter, {appIdExpr}, {urlArg}, null{patchContentTypeArg});",

                "DELETE" => bodyParam is not null
                    ? $"var res = await client.HttpDelete<{returnArg}, {bodyParam.Type}>(_clientAdapter, {appIdExpr}, {urlArg}, {bodyParam.Name});"
                    : $"var res = await client.HttpDelete<{returnArg}>(_clientAdapter, {appIdExpr}, {urlArg});",

                "HttpFileUpload" or "HttpFileUploadStream" => GenerateUploadCall(returnArg, appIdExpr, urlArg, parameters),

                "HttpResponseMessage" => GenerateHttpResponseMessageCall(httpMethodValue, returnArg, bodyParam, appIdExpr, urlArg),

                _ => $"var res = await client.HttpGet<{returnArg}>(_clientAdapter, {appIdExpr}, {urlArg});",
            };
        }

        private static string GenerateUploadCall(string returnArg, string appIdExpr, string urlArg, List<GeneratedParam> parameters)
        {
            var filepathParam = parameters.FirstOrDefault(p => p.IsFilePath);
            var formDataParam = parameters.FirstOrDefault(p => !p.IsFilePath);
            var filepath = filepathParam?.Name ?? "filepath";
            if (formDataParam is not null)
            {
                return $"var res = await client.UploadFile<{returnArg}>(_clientAdapter, {appIdExpr}, {urlArg}, {filepath}, {formDataParam.Name});";
            }
            return $"var res = await client.UploadFile<{returnArg}>(_clientAdapter, {appIdExpr}, {urlArg}, {filepath});";
        }

        private static string GenerateHttpResponseMessageCall(string httpMethodValue, string returnArg, GeneratedParam bodyParam, string appIdExpr, string urlArg)
        {
            var type = string.IsNullOrWhiteSpace(bodyParam?.Type) ? returnArg : bodyParam!.Type;
            var obj = bodyParam?.Name ?? "null";
            var method = GetHttpMethodNameText(httpMethodValue);
            return $"var res = await client.HttpResponseMessageAsync<{type}>(_clientAdapter, {appIdExpr}, {urlArg}, HttpMethod.{method}, {obj});";
        }

        private static string GetReturnTypeArgument(MethodDeclarationSyntax methodSyntax)
        {
            if (methodSyntax.ReturnType is GenericNameSyntax { TypeArgumentList.Arguments.Count: > 0 } generic)
            {
                return generic.TypeArgumentList.Arguments[0].ToString().Trim();
            }
            return "object";
        }

        private static string GetHttpMethodName(IMethodSymbol method)
        {
            foreach (var attribute in method.GetAttributes())
            {
                var name = attribute.AttributeClass?.Name;
                return name switch
                {
                    "HttpGetAttribute" => "GET",
                    "HttpPostAttribute" => "POST",
                    "HttpPutAttribute" => "PUT",
                    "HttpDeleteAttribute" => "DELETE",
                    "HttpPatchAttribute" => "Patch",
                    "HttpResponseMessageAttribute" => "HttpResponseMessage",
                    "HttpFileUploadAttribute" or "HttpFileUploadStreamAttribute" => "HttpFileUpload",
                    _ => "GET",
                };
            }
            return "GET";
        }

        private static string GetHttpMethodNameText(string httpMethodValue)
        {
            return httpMethodValue switch
            {
                "0" or "Get" => "Get",
                "1" or "Post" => "Post",
                "2" or "Put" => "Put",
                "3" or "Delete" => "Delete",
                "4" or "Patch" => "Patch",
                _ => "Get",
            };
        }

        private static List<GeneratedParam> GetParameters(MethodDeclarationSyntax methodSyntax, IMethodSymbol methodSymbol)
        {
            var symbols = methodSymbol.Parameters;
            var result = new List<GeneratedParam>();
            foreach (var parameterSyntax in methodSyntax.ParameterList.Parameters)
            {
                var symbol = symbols.FirstOrDefault(p => p.Name == parameterSyntax.Identifier.ValueText);
                result.Add(new GeneratedParam
                {
                    Name = parameterSyntax.Identifier.ValueText,
                    Type = parameterSyntax.Type?.ToString().Trim() ?? "object",
                    IsPath = symbol?.GetAttributes().Any(a => a.AttributeClass?.Name == "PathVariableAttribute") ?? false,
                    IsFilePath = symbol?.GetAttributes().Any(a => a.AttributeClass?.Name == "FilePathVariableAttribute") ?? false,
                });
            }
            return result;
        }

        private static List<string> GetUsings(INamedTypeSymbol interfaceSymbol)
        {
            var usings = new List<string>(interfaceSymbol.GetUsings());
            foreach (var ns in ExtraUsings)
            {
                if (!usings.Contains(ns))
                {
                    usings.Add(ns);
                }
            }
            return usings;
        }

        private static string GenerateServiceCollectionExtSource(List<INamedTypeSymbol> interfaces)
        {
            var builder = new AdvancedExtensionBuilder();
            builder
                .WithNullable()
                .AppendAutoGeneratedComment()
                .WithUsingsList(
                [
                    "System",
                    "System.Linq",
                    "FluentHttp.Ext",
                    "Microsoft.Extensions.DependencyInjection",
                    "Microsoft.Extensions.DependencyInjection.Extensions",
                ])
                .BeginNamespace("FluentHttp.Ext")
                .BeginClassType("public static partial class ServiceCollectionExtG");

            builder.WithBlock(
                "public static IServiceCollection AddFluentHttp(this IServiceCollection services, ServiceLifetime lifetime = ServiceLifetime.Scoped)",
                b =>
                {
                    foreach (var interfaceSymbol in interfaces)
                    {
                        b.WithLine($"services.TryAdd(ServiceDescriptor.Describe(typeof({interfaceSymbol.ContainingNamespace.ToDisplayString()}.{interfaceSymbol.Name}), typeof({interfaceSymbol.ContainingNamespace.ToDisplayString()}.{GetImplClassName(interfaceSymbol)}), lifetime));");
                    }
                    b.WithLine("return services;");
                });

            return builder.EndClass().EndNamespace().ToString();
        }

        private static string GetImplClassName(INamedTypeSymbol interfaceSymbol)
        {
            var name = GetNamedArgumentValue(interfaceSymbol, DaprConst.Name);
            if (!string.IsNullOrWhiteSpace(name))
            {
                return name;
            }
            var interfaceName = interfaceSymbol.Name;
            return interfaceName.Length > 1 && interfaceName.StartsWith("I", StringComparison.Ordinal)
                ? interfaceName.Substring(1)
                : interfaceName;
        }

        private static string EscapeStringLiteral(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        private static string GetNamedArgumentValue(ISymbol symbol, string name)
        {
            foreach (var attribute in symbol.GetAttributes())
            {
                foreach (var pair in attribute.NamedArguments)
                {
                    if (pair.Key == name)
                    {
                        return pair.Value.Value?.ToString() ?? string.Empty;
                    }
                }
            }
            return string.Empty;
        }

        private sealed class GeneratedParam
        {
            public string Name { get; set; } = string.Empty;

            public string Type { get; set; } = "object";

            public bool IsPath { get; set; }

            public bool IsFilePath { get; set; }
        }

        #endregion
    }
}
