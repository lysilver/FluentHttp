using Microsoft.CodeAnalysis.CSharp;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace FluentHttp.SourceGenerator.Core
{
    public class AdvancedExtensionBuilder
    {
        private readonly StringBuilder _builder = new();
        private int _indentLevel = 0;
        private const string IndentUnit = "    "; // 四个空格为单位
        private int _extraIndent = 0;
        private bool _autoNewLine = false;
        private readonly List<string> _usings = [];

        public AdvancedExtensionBuilder WithUsing(string usingNamespace)
        {
            _usings.Add(usingNamespace);
            return this;
        }

        public AdvancedExtensionBuilder WithUsing(bool flag, string usingNamespace)
        {
            if (flag)
            {
                _usings.Add(usingNamespace);
            }
            return this;
        }

        public AdvancedExtensionBuilder WithUsings(params string[] namespaces)
        {
            _usings.AddRange(namespaces);
            return this;
        }

        public AdvancedExtensionBuilder WithUsingsList(List<string> namespaces)
        {
            _usings.AddRange(namespaces);
            return this;
        }

        public AdvancedExtensionBuilder WithExtraIndent(int spaces)
        {
            _extraIndent = spaces;
            return this;
        }

        public AdvancedExtensionBuilder EnableAutoNewLine(bool enable = true)
        {
            _autoNewLine = enable;
            return this;
        }

        public AdvancedExtensionBuilder AppendAutoGeneratedComment() => WithLine("// <auto-generated/>");

        public AdvancedExtensionBuilder WithLine(string content = "")
        {
            string padding = new(' ', _indentLevel * IndentUnit.Length + _extraIndent);
            _builder.AppendLine($"{padding}{content}");
            if (_autoNewLine)
            {
                _builder.AppendLine();
            }
            return this;
        }

        public AdvancedExtensionBuilder WithNullable() => WithLine("#nullable enable");


        public AdvancedExtensionBuilder WithLine(Action<AdvancedExtensionBuilder> action)
        {
            action?.Invoke(this);
            return this;
        }

        public AdvancedExtensionBuilder WithLine(bool flag, string content = "")
        {
            if (flag)
            {
                WithLine(content);
            }
            return this;
        }

        public AdvancedExtensionBuilder WithLines(IEnumerable<string> codes)
        {
            foreach (var code in codes)
            {
                if (!string.IsNullOrWhiteSpace(code))
                {
                    WithLine(code);
                }
            }
            return this;
        }

        public AdvancedExtensionBuilder WithAggressiveInlining(bool flag = true)
        {
            if (flag)
            {
                WithLine("[System.Runtime.CompilerServices.MethodImpl(System.Runtime.CompilerServices.MethodImplOptions.AggressiveInlining)]");
            }
            return this;
        }

        public AdvancedExtensionBuilder WithLeftBracket()
        {
            WithLine("{");
            return this;
        }

        public AdvancedExtensionBuilder WithRightBracket()
        {
            WithLine("}");
            return this;
        }

        public AdvancedExtensionBuilder WithRightBracketColon()
        {
            WithLine("};");
            return this;
        }

        public AdvancedExtensionBuilder WithIndentedLines(Action innerLines)
        {
            WithLine("{");
            _indentLevel++;
            innerLines();
            _indentLevel--;
            WithLine("}");
            return this;
        }


        public AdvancedExtensionBuilder WithIndentedLines(IEnumerable<string> lines)
        {
            WithLine("{");
            _indentLevel++;
            foreach (var line in lines)
            {
                WithLine(line);
            }
            _indentLevel--;
            WithLine("}");
            return this;
        }

        public AdvancedExtensionBuilder WithSmartLine(string content)
        {
            bool isSwitchCase = content.TrimStart().StartsWith("case") || content.Contains("=>");
            int indent = _indentLevel * IndentUnit.Length + _extraIndent + (isSwitchCase ? IndentUnit.Length : 0);
            string padding = new(' ', indent);
            _builder.AppendLine($"{padding}{content}");

            if (_autoNewLine)
            {
                _builder.AppendLine();
            }
            return this;
        }

        public AdvancedExtensionBuilder WithCommaLines<T>(IEnumerable<T> items, Func<T, string> formatter)
        {
            var list = items.ToList();
            int count = list.Count;
            for (int i = 0; i < count; i++)
            {
                var suffix = i == count - 1 ? "" : ",";
                WithLine($"{formatter(list[i])}{suffix}");
            }
            return this;
        }

        public AdvancedExtensionBuilder WithComment(string comment, bool isMultiline = false)
        {
            string indent = new(' ', _indentLevel * IndentUnit.Length + _extraIndent);
            string line = isMultiline ? $"/* {comment} */" : $"// {comment}";
            _builder.AppendLine($"{indent}{line}");
            if (_autoNewLine)
            {
                _builder.AppendLine();
            }
            return this;
        }

        public AdvancedExtensionBuilder WithSummaryComment(string summary)
        {
            WithLine("/// <summary>");
            WithLine($"/// {summary}");
            WithLine("/// </summary>");
            return this;
        }

        public AdvancedExtensionBuilder WithRegion(string name, Action<AdvancedExtensionBuilder> contentBuilder)
        {
            WithLine($"#region {name}");
            contentBuilder(this); // 执行子内容
            WithLine($"#endregion {name}");
            if (_autoNewLine)
            {
                _builder.AppendLine();
            }
            return this;
        }

        public AdvancedExtensionBuilder WithBlock(string header, Action<AdvancedExtensionBuilder> contentBuilder)
        {
            WithLine(header);
            WithLine("{");
            _indentLevel++;
            contentBuilder(this);
            _indentLevel--;
            WithLine("}");
            return this;
        }

        public AdvancedExtensionBuilder WithClass(bool flag, string content = "")
        {
            if (flag)
            {
                WithLine(content);
            }
            return this;
        }

        public AdvancedExtensionBuilder WithMethod(Action<AdvancedExtensionBuilder> contentBuilder)
        {
            contentBuilder(this);
            return this;
        }

        public AdvancedExtensionBuilder WithLines(Action<AdvancedExtensionBuilder> contentBuilder)
        {
            contentBuilder(this);
            return this;
        }

        public AdvancedExtensionBuilder WithMethod(string signature, Action<AdvancedExtensionBuilder> body) =>
        WithBlock(signature, body);

        public AdvancedExtensionBuilder WithMethod(bool flag, string signature, Action<AdvancedExtensionBuilder> body)
        {
            return flag ? WithBlock(signature, body) : this;
        }

        public AdvancedExtensionBuilder WithProperty(string type, string name, string access = "public", string? init = null)
        {
            var suffix = init != null ? $" = {init};" : ";";
            return WithLine($"{access} {type} {name}{suffix}");
        }

        public AdvancedExtensionBuilder BeginClass(string className, string accessibility = "public static partial")
        {
            WithLine($"{accessibility} class {className}");
            WithLine("{");
            _indentLevel++;
            return this;
        }

        public AdvancedExtensionBuilder BeginClassType(string classType)
        {
            WithLine($"{classType}");
            WithLine("{");
            _indentLevel++;
            return this;
        }

        public AdvancedExtensionBuilder EndClass()
        {
            _indentLevel--;
            WithLine("}");
            return this;
        }

        public AdvancedExtensionBuilder WithSwitch(string expression, Action<SwitchBuilder> configure)
        {
            var switchBuilder = new SwitchBuilder(expression, this);
            configure(switchBuilder);
            switchBuilder.Build();
            return this;
        }

        public AdvancedExtensionBuilder WithFix()
        {
            this.WithLine();
            return this;
        }

        public AdvancedExtensionBuilder BeginNamespace(string ns)
        {
            WriteUsings(); // 插入 using 语句
            WithLine($"namespace {ns}");
            WithLine("{");
            _indentLevel++;
            return this;
        }

        public AdvancedExtensionBuilder BeginNamespaceNotUsing(string ns)
        {
            WithLine($"namespace {ns}");
            WithLine("{");
            _indentLevel++;
            return this;
        }

        public AdvancedExtensionBuilder BeginNamespaceUsing(string ns)
        {
            WithLine($"namespace {ns}");
            WithLine("{");
            _indentLevel++;
            foreach (var t in _usings.Distinct().OrderBy(c => c))
            {
                WithLine($"using {t};");
            }
            WithLine();
            return this;
        }

        public AdvancedExtensionBuilder EndNamespace()
        {
            _indentLevel--;
            WithLine("}");
            return this;
        }

        private void WriteUsings()
        {
            foreach (var ns in _usings.Distinct().OrderBy(c => c))
            {
                if (!string.IsNullOrWhiteSpace(ns))
                {
                    _builder.AppendLine($"using {ns};");
                }
            }
            _builder.AppendLine(); // 添加空行分隔
        }

        public override string ToString() => _builder.ToString();

        public string ToString2()
        {
            return CSharpSyntaxTree.ParseText(_builder.ToString())
            .GetRoot()
            // .NormalizeWhitespace()
            .SyntaxTree.GetText().ToString();
        }

        public class SwitchBuilder
        {
            private readonly List<string> _cases = [];
            private readonly AdvancedExtensionBuilder _builder;
            private readonly string _expression;

            public SwitchBuilder(string expression, AdvancedExtensionBuilder builder)
            {
                _expression = expression;
                _builder = builder;
            }

            public void WithCase(string match, string result)
            {
                _cases.Add($"    {match} => {result},");
            }

            public void WithDefault(string match, string result)
            {
                _cases.Add($"    {match} => {result}");
            }

            public void Build()
            {
                _builder.WithLine($"return {_expression} switch");
                _builder.WithLine("{");
                foreach (var line in _cases)
                {
                    _builder.WithLine(line);
                }
                _builder.WithLine("};");
            }
        }
    }
}